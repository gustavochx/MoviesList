    nonisolated public static let screenTitle: Font = .title2.bold()
    nonisolated public static let sectionTitle: Font = .headline
    nonisolated public static let meta: Font = .subheadline
    nonisolated public static let footnote: Font = .footnote
    nonisolated public static let captionStrong: Font = .caption.bold()
    nonisolated public static let caption2: Font = .caption2
}
